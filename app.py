def generate_fgsm(
    model,
    image,
    epsilon=4 / 255
):

    x = image.clone().detach()

    x.requires_grad = True

    output = model(x)

    label = output.argmax(
        dim=1
    )

    loss = F.cross_entropy(
        output,
        label
    )

    model.zero_grad()

    loss.backward()

    adv = (
        x +
        epsilon *
        x.grad.sign()
    )

    adv = torch.clamp(
        adv,
        -1,
        1
    )

    return adv.detach()


def generate_pgd(
    model,
    image,
    epsilon=8 / 255,
    alpha=2 / 255,
    steps=5
):

    original = image.clone().detach()

    x = original.clone().detach()

    x.requires_grad = True

    with torch.no_grad():

        label = model(
            original
        ).argmax(
            dim=1
        )

    for _ in range(steps):

        x.requires_grad = True

        output = model(x)

        loss = F.cross_entropy(
            output,
            label
        )

        model.zero_grad()

        loss.backward()

        x = (
            x +
            alpha *
            x.grad.sign()
        ).detach()

        delta = torch.clamp(
            x - original,
            -epsilon,
            epsilon
        )

        x = torch.clamp(
            original + delta,
            -1,
            1
        ).detach()

    return x


def generate_patch(
    image,
    patch_size=28,
    intensity=0.9
):

    adv = image.clone().detach()

    _, _, h, w = adv.shape

    start_y = (
        h - patch_size
    ) // 2

    start_x = (
        w - patch_size
    ) // 2

    # normalized tensor:
    # intensity 0.9 -> approximately bright
    normalized_intensity = (
        intensity * 2
    ) - 1

    adv[
        :,
        :,
        start_y:start_y + patch_size,
        start_x:start_x + patch_size
    ] = normalized_intensity

    return adv


