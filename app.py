def victim_prediction(
    model,
    image
):

    with torch.no_grad():

        output = model(image)

        probability = torch.softmax(
            output,
            dim=1
        )

        confidence, predicted = torch.max(
            probability,
            dim=1
        )

    return (
        predicted.item(),
        confidence.item()
    )


