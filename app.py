def tensor_to_image(tensor):

    image = tensor.detach().cpu()

    image = image.squeeze(0)

    image = image * 0.5 + 0.5

    image = torch.clamp(
        image,
        0,
        1
    )

    image = image.permute(
        1, 2, 0
    ).numpy()

    return image


